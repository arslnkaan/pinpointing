        linewidth = 0.3
      ),

      panel.grid.major.x = element_blank(),

      panel.grid.minor = element_blank(),

      panel.border = element_rect(
        fill = NA,
        color = "grey60",
        linewidth = 0.35
      ),

      panel.spacing.x = unit(
        0.50,
        "lines"
      ),

      strip.background = element_rect(
        fill = "grey96",
        color = "grey60",
        linewidth = 0.35
      ),

      strip.text = element_text(
        face = "bold",
        size = 11
      ),

      plot.title = element_text(
        hjust = 0.5,
        face = "bold",
        size = 13
      ),

      plot.subtitle = element_text(
        hjust = 0.5,
        size = 8.5
      )
    )

  safe_timepoint_name <- selected_timepoint %>%
    str_replace_all(
      "\\.",
      "p"
    )

  ggsave(
    filename = file.path(
      outdir,
      paste0(
        "UVCPD_WT_CSB_DDB2_XPC_",
        safe_timepoint_name,
        "_quartile_violin.pdf"
      )
    ),
    plot = p_timepoint,
    width = 10.0,
