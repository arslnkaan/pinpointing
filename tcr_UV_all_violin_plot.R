)

main_png_file <- file.path(
  outdir,
  "UVCPD_WT_CSB_DDB2_XPC_TS_NTS_quartile_violin_plots.png"
)

ggsave(
  filename = main_pdf_file,
  plot = violin_plot,
  width = 10.0,
  height = 8.3,
  units = "in",
  device = cairo_pdf
)

ggsave(
  filename = main_png_file,
  plot = violin_plot,
  width = 10.0,
  height = 8.3,
  units = "in",
  dpi = 600,
  bg = "white"
)

# ============================================================
# ONE FIGURE PER TIMEPOINT
#
# Columns:
#   WT, CSB, DDB2, XPC
#
# X-axis:
#   Q0-Q4
#
# The shared y-axis from the main figure is retained.
# ============================================================

save_one_timepoint_plot <- function(
  selected_timepoint
) {

  current_plot_data <- violin_plot_data %>%
    filter(
      as.character(timepoint) ==
        selected_timepoint
    )

  current_summary <- violin_summary %>%
    filter(
      as.character(timepoint) ==
        selected_timepoint
    )

  p_timepoint <- ggplot(
    current_plot_data,
    aes(
      x = quartile,
      y = mean_log2_TS_over_NTS,
      fill = timepoint
    )
  ) +

    geom_hline(
      yintercept = 0,
      linetype = "dashed",
      color = "black",
      linewidth = 0.45
    ) +

    geom_violin(
      width = 0.88,
      scale = "width",
      trim = TRUE,
      adjust = density_adjust,
      color = "black",
      linewidth = 0.28,
      alpha = 0.84,
      na.rm = TRUE
    ) +

    geom_segment(
      data = current_summary,
      aes(
        x = quartile,
        xend = quartile,
        y = q1_log2_TS_NTS,
        yend = q3_log2_TS_NTS
      ),
      inherit.aes = FALSE,
      linewidth = 1.5,
      color = "black",
      lineend = "round"
    ) +

    geom_crossbar(
      data = current_summary,
      aes(
        x = quartile,
        y = median_log2_TS_NTS,
        ymin = median_log2_TS_NTS,
        ymax = median_log2_TS_NTS
      ),
      inherit.aes = FALSE,
      width = 0.34,
      linewidth = 0.65,
      color = "white"
    ) +

    facet_grid(
      cols = vars(
        genotype
      )
    ) +

    scale_fill_manual(
      values = time_colors,
      breaks = time_order,
      drop = FALSE
    ) +

    scale_x_discrete(
      limits = quartile_order,
      drop = FALSE
    ) +

    scale_y_continuous(
      breaks = pretty(
        c(
          violin_ymin,
          violin_ymax
        ),
        n = 7
      ),

      expand = expansion(
        mult = c(
          0.02,
          0.02
        )
      )
    ) +

    coord_cartesian(
      ylim = c(
        violin_ymin,
        violin_ymax
      ),
      clip = "off"
    ) +

    labs(
      x = "Expression quartile",

      y = expression(
        mean ~ log[2] *
          frac(
            allTS + 0.5,
            allNTS + 0.5
          )
      ),

      title = paste0(
        "UV-CPD transcription-coupled repair — ",
        selected_timepoint
      ),

      subtitle = paste0(
        "Gene-level R1/R2 mean; ",
